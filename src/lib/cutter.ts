/**
 * Triggers an authoritative, type-safe browser file download.
 * Enforces filename extension == format == Blob MIME type == generated bytes.
 */
export function downloadFile(
  bytes: Uint8Array | Blob,
  filename: string,
  format?: CanonicalFormat
): DownloadContract {
  return triggerDownload({ bytes, filename, format });
}

/**
 * Generates a ZIP archive containing all generated files.
 * Deduplicates filenames case-insensitively so duplicate names never silently overwrite entries.
 */
export async function createZipBundle(
  items: Array<{ filename: string; bytes: Uint8Array }>
): Promise<Blob> {
  const zip = new JSZip();
  const usedLowerNames = new Set<string>();

  items.forEach((item) => {
    const baseName = sanitizeDownloadFilename(item.filename, 'pdf');
    let finalName = baseName;
    let counter = 1;

    // Deduplicate case-insensitively: "Unit 1.pdf" vs "unit 1.PDF"
    while (usedLowerNames.has(finalName.toLowerCase())) {
      const extMatch = baseName.match(/\.[^.]+$/);
      const ext = extMatch ? extMatch[0] : '.pdf';
      const root = baseName.substring(0, baseName.length - ext.length);
      finalName = `${root} (${counter})${ext}`;
      counter++;
    }

    usedLowerNames.add(finalName.toLowerCase());
    zip.file(finalName, item.bytes);
  });

  return await zip.generateAsync({
    type: 'blob',
    compression: 'DEFLATE',
    compressionOptions: { level: 6 },
  });
}

/**
 * Checks whether the browser supports the File System Access API
 */
export function isFileSystemAccessSupported(): boolean {
  return typeof window !== 'undefined' && 'showDirectoryPicker' in window;
}

/**
 * Saves generated files directly to a folder chosen by the user via File System Access API.
 * Retains and reuses existing directory handles to prevent multiple prompts.
 */
export async function saveFilesToDirectory(
  items: Array<{ filename: string; bytes: Uint8Array }>,
  promptConflictAction?: (filename: string) => Promise<'replace' | 'rename' | 'cancel'>,
  existingDirHandle?: any
): Promise<{ savedCount: number; errors: string[]; dirHandle?: any }> {
  if (!isFileSystemAccessSupported()) {
    throw new Error('File System Access API is not supported in this browser.');
  }

  let dirHandle = existingDirHandle;
  if (!dirHandle) {
    dirHandle = await (window as any).showDirectoryPicker({
      mode: 'readwrite',
    });
  } else {
    // Verify existing permission
    try {
      if (typeof dirHandle.queryPermission === 'function') {
        let perm = await dirHandle.queryPermission({ mode: 'readwrite' });
        if (perm !== 'granted' && typeof dirHandle.requestPermission === 'function') {
          perm = await dirHandle.requestPermission({ mode: 'readwrite' });
        }
        if (perm !== 'granted') {
          dirHandle = await (window as any).showDirectoryPicker({ mode: 'readwrite' });
        }
      }
    } catch {
      dirHandle = await (window as any).showDirectoryPicker({ mode: 'readwrite' });
    }
  }

  let savedCount = 0;
  const errors: string[] = [];
  const batchLowerNames = new Set<string>();

  for (const item of items) {
    let targetName = sanitizeDownloadFilename(item.filename, 'pdf');

    // Prevent in-batch collisions
    const baseTarget = targetName;
    let batchCounter = 1;
    while (batchLowerNames.has(targetName.toLowerCase())) {
      const ext = baseTarget.match(/\.[^.]+$/)?.[0] || '.pdf';
      const root = baseTarget.substring(0, baseTarget.length - ext.length);
      targetName = `${root} (${batchCounter})${ext}`;
      batchCounter++;
    }
    batchLowerNames.add(targetName.toLowerCase());

    // Check if file already exists in target directory
    let fileExists = false;
    try {
      await dirHandle.getFileHandle(targetName);
      fileExists = true;
    } catch {
      fileExists = false;
    }

    if (fileExists && promptConflictAction) {
      const action = await promptConflictAction(targetName);
      if (action === 'cancel') {
        continue; // Skip this file
      } else if (action === 'rename') {
        let counter = 1;
        const ext = targetName.match(/\.[^.]+$/)?.[0] || '.pdf';
        const nameWithoutExt = targetName.replace(new RegExp(`\\${ext}$`, 'i'), '');
        while (fileExists && counter < 50) {
          targetName = `${nameWithoutExt} (${counter})${ext}`;
          try {
            await dirHandle.getFileHandle(targetName);
            counter++;
          } catch {
            fileExists = false;
          }
        }
      }
    }

    try {
      const fileHandle = await dirHandle.getFileHandle(targetName, { create: true });
      const writable = await fileHandle.createWritable();
      await writable.write(item.bytes);
      await writable.close();
      savedCount++;
    } catch (err: any) {
      errors.push(`Failed to save "${targetName}": ${err.message || err}`);
    }
  }

  return { savedCount, errors, dirHandle };
}

export interface CutExecutionOptions {
  isUncertain: boolean;
  isConfirmed: boolean;
}

/**
 * Resolves effective uncertainty:
 * - In manual mode: explicitly returns false (user-defined ranges).
 * - In auto mode: strictly requires a valid boolean; throws if undefined, null, or invalid.
 */
export function resolveEffectiveUncertainty(
  splitMode: 'auto' | 'manual',
  isUncertain: boolean | undefined | null
): boolean {
  if (splitMode === 'manual') {
    return false;
  }
  if (typeof isUncertain !== 'boolean') {
    throw new Error(
      'Cannot execute cut: Automatic detection uncertainty state is missing or invalid. Please re-run analysis or switch to Manual Split.'
    );
  }
  return isUncertain;
}

export interface CutDispatchParams {
  buffer: ArrayBuffer | Uint8Array | null;
  parts: DetectedPart[];
  isValidRanges: boolean;
  isUncertain: boolean;
  isBoundariesConfirmed: boolean;
  onProgress?: (state: CutProgressState) => void;
  shouldCancel?: () => boolean;
}

/**
 * High-level cut execution controller used by handleCutPdf to enforce
 * fail-closed safety guards for uncertain documents.
 */
export async function dispatchCutExecution(params: CutDispatchParams): Promise<CutProgressItem[]> {
  if (
    !params ||
    typeof params.isUncertain !== 'boolean' ||
    typeof params.isBoundariesConfirmed !== 'boolean'
  ) {
    throw new Error(
      'Cannot execute cut: Execution safety parameters { isUncertain, isBoundariesConfirmed } are mandatory and must be explicitly provided.'
    );
  }
  if (!params.buffer || params.parts.length === 0) {
    throw new Error('Cannot execute cut: PDF document or parts list is empty.');
  }
  if (!params.isValidRanges) {
    throw new Error('Cannot execute cut: Page ranges contain validation errors.');
  }
  if (params.isUncertain && params.isBoundariesConfirmed !== true) {
    throw new Error(
      'Cannot execute cut: Uncertain page boundaries must be reviewed and confirmed before cutting.'
    );
  }
  return executeCutPlan(
    params.buffer,
    params.parts,
    params.onProgress || (() => {}),
    params.shouldCancel || (() => false),
    {
      isUncertain: params.isUncertain,
      isConfirmed: params.isBoundariesConfirmed,
    }
  );
}

/**
 * Slices all parts with responsive asynchronous progress updates
 */
export async function executeCutPlan(
  sourceBytes: ArrayBuffer | Uint8Array,
  parts: DetectedPart[],
  onProgress: (state: CutProgressState) => void,
  shouldCancel: (() => boolean) | undefined,
  options: CutExecutionOptions
): Promise<CutProgressItem[]> {
  if (
    !options ||
    typeof options.isUncertain !== 'boolean' ||
    typeof options.isConfirmed !== 'boolean'
  ) {
    throw new Error(
      'Cannot execute cut: Execution safety options { isUncertain, isConfirmed } are mandatory and must be explicitly provided.'
    );
  }

  if (options.isUncertain && options.isConfirmed !== true) {
    throw new Error(
      'Cannot execute cut: Uncertain page boundaries must be reviewed and confirmed before cutting.'
    );
  }

  const items: CutProgressItem[] = parts.map((part) => ({
    id: part.id,
    title: part.title,
    filename: part.filename,
    status: 'waiting',
    progress: 0,
  }));

  const state: CutProgressState = {
    isCutting: true,
    currentIndex: 0,
    total: items.length,
    items,
    completedCount: 0,
    isCancelled: false,
  };

  onProgress({ ...state });

  // Load the source PDF once to avoid re-parsing on every part
  if (!sourceBytes || sourceBytes.byteLength === 0) {
    throw new Error('Cannot execute cut: PDF buffer is empty or detached.');
  }
  const safeBytes = sourceBytes.slice(0);
  const srcDoc = await PDFDocument.load(safeBytes);
  const totalPages = srcDoc.getPageCount();

  const cancelCheck = shouldCancel || (() => false);

  const abortRemaining = (fromIndex: number) => {
    state.isCancelled = true;
    state.isCutting = false;
    for (let j = fromIndex; j < items.length; j++) {
      if (items[j].status === 'waiting' || items[j].status === 'processing') {
        items[j].status = 'error';
        items[j].error = 'Cancelled by user';
      }
    }
    onProgress({ ...state, items: [...items] });
  };

  for (let i = 0; i < parts.length; i++) {
    if (cancelCheck()) {
      abortRemaining(i);
      break;
    }

    state.currentIndex = i;
    items[i].status = 'processing';
    items[i].progress = 25;
    onProgress({ ...state, items: [...items] });

    // Yield control to UI thread
    await new Promise((r) => setTimeout(r, 15));

    if (cancelCheck()) {
      abortRemaining(i);
      break;
    }

    try {
      const part = parts[i];
      if (
        part.startPage < 1 ||
        part.endPage < part.startPage ||
        part.startPage > totalPages ||
        part.endPage > totalPages
      ) {
        throw new Error(
          `Invalid page range [${part.startPage}..${part.endPage}] for "${part.title}". Document has ${totalPages} pages.`
        );
      }

      const expectedPageCount = part.endPage - part.startPage + 1;
      const pageIndices: number[] = [];
      for (let p = part.startPage; p <= part.endPage; p++) {
        pageIndices.push(p - 1);
      }

      items[i].progress = 50;
      onProgress({ ...state, items: [...items] });
      await new Promise((r) => setTimeout(r, 10));

      if (cancelCheck()) {
        abortRemaining(i);
        break;
      }

      const subDoc = await PDFDocument.create();
      const copiedPages = await subDoc.copyPages(srcDoc, pageIndices);
      copiedPages.forEach((page) => subDoc.addPage(page));

      items[i].progress = 85;
      onProgress({ ...state, items: [...items] });
      await new Promise((r) => setTimeout(r, 10));

      if (cancelCheck()) {
        abortRemaining(i);
        break;
      }

      const pdfBytes = await subDoc.save();

      // Strict physical verification: reopen generated PDF bytes and verify exact page count
      const verifyDoc = await PDFDocument.load(pdfBytes);
      const actualCount = verifyDoc.getPageCount();
      if (actualCount !== expectedPageCount) {
        throw new Error(
          `Verification failed for "${part.title}": Expected ${expectedPageCount} pages, but generated PDF has ${actualCount} pages.`
        );
      }

      items[i].bytes = pdfBytes;
      items[i].status = 'done';
      items[i].progress = 100;
      state.completedCount++;
      onProgress({ ...state, items: [...items] });
    } catch (err: any) {
      items[i].status = 'error';
      items[i].error = err.message || 'Error creating PDF slice';
      onProgress({ ...state, items: [...items] });
    }

    // Yield to allow UI rendering
    await new Promise((r) => setTimeout(r, 15));
  }

  state.isCutting = false;
  if (cancelCheck()) {
    state.isCancelled = true;
  }
  onProgress({ ...state, items: [...items] });

  return items;
}
